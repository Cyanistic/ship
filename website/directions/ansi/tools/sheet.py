"""Write art.html, a review sheet of every drawing in art/ at the page's pixel size.

usage: python3 tools/sheet.py [names...]

With no names it writes art.html (every sprite, grouped, on the ground it is used on).
With names (for example `crate barrel bucket`) it writes /tmp/ansi-sheet.html instead, a
quick look at just those, which tools/shot.py can capture.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, "art")

GROUPS = [
    ("crew, neutral and in the five states", r"^crew-(?!diver)[a-z]+-(neutral|working|blocked|unseen|idle|error)(-b)?$", "#e4f2f8"),
    ("crew, extra poses", r"^crew-[a-z]+-(reach|lantern|clipboard|point)$", "#e4f2f8"),
    ("crew loops: sheets of frames, one frame per step", r"^crew-(?!diver)[a-z]+-[a-z]+-loop$", "#e4f2f8"),
    ("crew, blink and glance", r"^crew-[a-z]+-neutral-(blink|glance)$|^face-", "#e4f2f8"),
    ("diver", r"^crew-diver", "#14306b"),
    ("sky and rigging", r"^(cloud|gull|crows-nest|spyglass|mast|mast-base|ratlines)", "#cfe7f3"),
    ("deck", r"^(planks|hull|rail|barrel|crate|crate-cargo|rope-coil|bucket|sack|ext)$", "#e4f2f8"),
    ("sea", r"^(wave|wave-back|bottle|buoy|float-plank|float-sign|fish|bubble)$", "#1f4fa8"),
    ("below deck", r"^(porthole|bulkhead|wall|beam|ladder|lantern|glow|steam|room-)", "#252232"),
    ("hold and seabed", r"^(pile|pile-small|keel|sand|kelp|crab|starfish|rocks|anchor|chain)$", "#0f1a38"),
]


def size(path):
    m = re.search(r'viewBox="0 0 (\d+) (\d+)"', open(path).read())
    return int(m[1]), int(m[2])


def main():
    names = sorted(f[:-4] for f in os.listdir(ART) if f.endswith(".svg"))
    only = sys.argv[1:]
    body = []
    if only:
        body.append('<section style="background:#e4f2f8"><h2>sample</h2><ul>')
        for n in only:
            w, h = size(os.path.join(ART, n + ".svg"))
            body.append(f'<li><img src="{ART}/{n}.svg" width="{w*4}" height="{h*4}" alt=""><code>{n} {w}x{h}</code></li>')
        body.append("</ul></section>")
        out = "/tmp/ansi-sheet.html"
    else:
        used = set()
        for title, rx, ground in GROUPS:
            hit = [n for n in names if re.search(rx, n) and n not in used]
            used.update(hit)
            body.append(f'<section style="background:{ground}"><h2>{title}</h2><ul>')
            for n in hit:
                w, h = size(os.path.join(ART, n + ".svg"))
                body.append(f'<li><img src="art/{n}.svg" width="{w*4}" height="{h*4}" alt=""><code>{n} {w}x{h}</code></li>')
            body.append("</ul></section>")
        rest = [n for n in names if n not in used]
        if rest:
            body.append('<section style="background:#e4f2f8"><h2>other</h2><ul>')
            for n in rest:
                w, h = size(os.path.join(ART, n + ".svg"))
                body.append(f'<li><img src="art/{n}.svg" width="{w*4}" height="{h*4}" alt=""><code>{n} {w}x{h}</code></li>')
            body.append("</ul></section>")
        out = os.path.join(ROOT, "art.html")
    html = f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><title>ship · ansi · art sheet</title>
<meta name="viewport" content="width=device-width, initial-scale=1">
<link rel="stylesheet" href="{'css/site.css' if not only else ROOT + '/css/site.css'}">
<style>
body{{margin:0;font:15px/1.4 var(--code)}} h1{{margin:0;padding:28px 28px 8px;background:var(--paper)}}
p.lead{{margin:0;padding:0 28px 22px;background:var(--paper);max-width:80ch;font-family:var(--read)}}
section{{padding:20px 28px 28px}} h2{{margin:0 0 14px;font:11px/22px var(--pixel);color:var(--ink)}}
ul{{list-style:none;margin:0;padding:0;display:flex;flex-wrap:wrap;gap:22px 28px;align-items:flex-end}}
li{{display:flex;flex-direction:column;gap:6px;max-width:100%;overflow-x:auto}} img{{image-rendering:pixelated}} code{{font-size:11px;color:var(--ink);background:none;padding:0}}
section[style*="#252232"] h2, section[style*="#252232"] code, section[style*="#0f1a38"] h2, section[style*="#0f1a38"] code,
section[style*="#14306b"] h2, section[style*="#14306b"] code, section[style*="#1f4fa8"] h2, section[style*="#1f4fa8"] code{{color:var(--c15)}}
</style></head><body>
<h1 class="pixel p33">art sheet</h1>
<p class="lead">every drawing in art/ at four screen pixels per art pixel, on the ground it sits on in the page. generated by tools/sheet.py. for review only; the site pages use the files directly.</p>
{chr(10).join(body)}
</body></html>"""
    open(out, "w").write(html)
    print(out, f"{len(names)} sprites" if not only else "")


main()
