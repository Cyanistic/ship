"""Test sheet for the large app mark: colour and one colour at 64, 128, 256 and
460px, on paper and on ink, beside the current 16 x 16 app mark at the same sizes, then the avatar variant
clipped to a circle as GitHub shows an org avatar.

usage: python3 website/tools/marks_large_sheet.py [out_dir]   (default /tmp/ship-mark-large)
Writes sheet.html and sheet.png into out_dir.
"""
import os
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
ANSI = os.path.join(HERE, "..", "directions", "ansi", "tools")
sys.path.insert(0, ANSI)
sys.path.insert(0, HERE)
import marks  # noqa: E402
from cdp import Page  # noqa: E402
from pixel import PALETTE  # noqa: E402
import marks_large  # noqa: E402

SIZES = (64, 128, 256, 460)
GROUNDS = (("paper", "#fbf8f1", PALETTE["0"]), ("ink", "#1c1a27", PALETTE["f"]))


def svgs():
    """(label, svg on paper, svg on ink, circle crop). One colour turns to paper on ink."""
    small, small_m = marks.colour("app"), marks.mono("app")
    g = marks_large.N
    large, large_m = marks_large.draw(), marks_large.draw(True)
    av, av_m = marks_large.avatar(), marks_large.avatar(True)
    t, u = "test", marks_large.UNIT
    ink, paper = PALETTE["0"], PALETTE["f"]
    return [
        ("current 16 x 16 app, colour", small.svg(unit=16, title=t), small.svg(unit=16, title=t), False),
        (f"large {g} x {g} app, colour", large.svg(unit=u, title=t), large.svg(unit=u, title=t), False),
        ("current 16 x 16 app, one colour", small_m.svg(unit=16, colors={"ink": ink}, title=t),
         small_m.svg(unit=16, colors={"ink": paper}, title=t), False),
        (f"large {g} x {g} app, one colour", large_m.svg(unit=u, colors={"#": ink}, title=t),
         large_m.svg(unit=u, colors={"#": paper}, title=t), False),
        (f"avatar {av.w} x {av.w}, colour, cropped to a circle", av.svg(unit=u, title=t), av.svg(unit=u, title=t), True),
        (f"avatar {av.w} x {av.w}, one colour, cropped to a circle", av_m.svg(unit=u, colors={"#": ink}, title=t),
         av_m.svg(unit=u, colors={"#": paper}, title=t), True),
    ]


def main(out):
    os.makedirs(out, exist_ok=True)
    rows = []
    for label, on_paper, on_ink, circle in svgs():
        for gname, bg, fg in GROUNDS:
            svg = on_paper if gname == "paper" else on_ink
            fn = f"{label.replace(' ', '-').replace(',', '')}-{gname}.svg"
            open(os.path.join(out, fn), "w").write(svg)
            cls = ' class="circle"' if circle else ""
            cells = "".join(
                f'<figure><img src="{fn}" width="{s}" height="{s}" alt=""{cls}><figcaption>{s}px</figcaption></figure>'
                for s in SIZES)
            rows.append(f'<section style="background:{bg};color:{fg}"><h2>{label} on {gname}</h2>'
                        f'<div class="row">{cells}</div></section>')
    html = f"""<!doctype html><html><head><meta charset="utf-8"><style>
body{{margin:0;font:13px/1.4 ui-monospace,Menlo,monospace;background:#cfe7f3}}
h1{{margin:0;padding:20px 24px 4px;font-size:18px}} p{{margin:0 24px 16px}}
section{{padding:14px 24px 18px}} h2{{margin:0 0 10px;font-size:12px;font-weight:normal}}
.row{{display:flex;gap:32px;align-items:flex-end}} figure{{margin:0}} img.circle{{border-radius:50%;outline:1px dashed #e65a48;outline-offset:0}} figcaption{{font-size:11px;opacity:.7}}
</style></head><body><h1>ship app mark, large vs current (16 x 16)</h1>
<p>generated by website/tools/marks_large_sheet.py. images are shown at true css pixels, browser scaling. avatar rows are clipped to a circle (border-radius 50%, dashed red ring) the way github crops an org avatar.</p>
{''.join(rows)}</body></html>"""
    path = os.path.join(out, "sheet.html")
    open(path, "w").write(html)
    page = Page(1180)
    try:
        page.goto(path, settle=1.0)
        h = page.full_page_png(os.path.join(out, "sheet.png"))
    finally:
        page.close()
    print(os.path.join(out, "sheet.png"), h)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "/tmp/ship-mark-large")
